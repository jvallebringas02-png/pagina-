// Mezcla las claves de AUTH_I18N dentro de UI_TRANSLATIONS (quechua y aimara no se tocan).
(function mezclarTraduccionesAuth() {
    if (typeof UI_TRANSLATIONS === 'undefined') { console.warn('i18n-auth.js: UI_TRANSLATIONS no existe; ¿se cargó después de i18n.js?'); return; }
    Object.keys(AUTH_I18N).forEach(function(lang) {
        UI_TRANSLATIONS[lang] = Object.assign(UI_TRANSLATIONS[lang] || {}, AUTH_I18N[lang]);
    });
})();

// Texto del modal de login en el idioma actual. `vars` reemplaza {p}, {m}, etc.
// Si el idioma no tiene la clave (quechua, aimara), cae al español de AUTH_I18N.es.
function tAuth(clave, vars) {
    var s = textoUI(clave, AUTH_I18N.es[clave] || clave);
    if (vars) Object.keys(vars).forEach(function(k) { s = s.split('{' + k + '}').join(vars[k]); });
    return s;
}

// Nombre del país en el idioma actual usando la traducción del propio navegador (Intl),
// así no hay que escribir 12 nombres x 15 idiomas. Quechua y aimara usan el español.
var PAISES_AUTH_ES = { PE: 'Perú', MX: 'México', CO: 'Colombia', AR: 'Argentina', CL: 'Chile', EC: 'Ecuador', BO: 'Bolivia', VE: 'Venezuela', ES: 'España', US: 'Estados Unidos', BR: 'Brasil', BG: 'Bulgaria' };
function nombrePaisAuth(codigo) {
    var lang = 'es';
    try { lang = obtenerIdiomaPreferido(); } catch (e) {}
    if (lang !== 'es' && lang !== 'qu' && lang !== 'ay' && typeof Intl !== 'undefined' && Intl.DisplayNames) {
        try { var n = new Intl.DisplayNames([lang], { type: 'region' }).of(codigo); if (n) return n; } catch (e) {}
    }
    return PAISES_AUTH_ES[codigo] || codigo;
}
